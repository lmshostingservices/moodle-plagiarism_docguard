/**
 * Authenticity findings: things present in a submission that should not be there, and
 * references in it that cannot be verified.
 *
 * WHAT THIS CLASS DELIBERATELY DOES NOT DO
 *
 * It does not measure how the writing reads. No sentence lengths, no vocabulary richness, no
 * marker words, no "this sounds like AI". Every one of those was measured and failed:
 *
 *  - The marker-word signals shipped to 1.0.98 flagged 0 of 48 answers generated by ChatGPT,
 *    Gemini and Claude, and found zero markers in 48 of 48. The highest-scoring document in
 *    that exercise was a human student writing in their second language.
 *  - Style statistics as absolute measures do not separate the classes: of eight measures
 *    tested, overlap between the human and AI ranges ran from 25% to 100%, and the single
 *    best one rested on a human baseline of eight documents, which is far too few to
 *    establish a range.
 *  - Comparing windows WITHIN one document - the most promising idea, because it needs no
 *    baseline - fails at assessment-answer length. Splitting 59 documents in half and
 *    comparing each author against themselves: one author's own variation between two halves
 *    of their own writing reached 36% on mean sentence length at the 90th percentile, where
 *    the median difference between two DIFFERENT authors was 20%. The same held for word
 *    length (17% vs 16%), vocabulary diversity (14% vs 8%) and long-word rate (90% vs 61%).
 *    A detector built on it flags normal writers for having written one answer in a hurry.
 *
 * So this class checks only things that are true or false about the file:
 *
 *  1. Conversational artefacts from a chat assistant, and prompt remnants. A student does not
 *     type "As an AI language model" or "Word count: 187" into an assessment.
 *  2. Markdown syntax inside a word-processed document, which indicates text composed
 *     somewhere else and pasted in.
 *  3. Legislation, standards and unit codes that do not exist. A fabricated Act section is a
 *     serious integrity finding whatever produced it.
 *  4. What the file itself records about how it was made.
 *
 * AND IT PRODUCES NO SCORE. Findings are returned individually, each with its own severity,
 * its location, and the evidence quoted verbatim. There is no composite number because there
 * is no honest way to weight these against each other yet: that requires calibration against
 * real student submissions, which this plugin has never had. A weighted total built from
 * guesses is how the previous version came to show a confident badge derived entirely from
 * signals that measured nothing.
 *
 * @package    plagiarism_docguard
 * @copyright  2026 LMS-Labs
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class authenticity {

    /**
     * @var int Version of the check set that produced a stored finding.
     *
     * Stamped on every row so that a report can say which checks ran, and so that adding or
     * removing a check later does not silently change the meaning of findings already in the
     * database. Raise it whenever a check is added, removed, or has its severity changed.
     */
    const CHECKS_VERSION = 1;

    /** @var string A finding that is decisive on its own and needs no corroboration. */
    const SEVERITY_STRONG = 'strong';


    /** @var string A finding worth a trainer's attention alongside others. */
    const SEVERITY_NOTABLE = 'notable';

    /** @var string Context only. Never sufficient to act on. */
    const SEVERITY_CONTEXT = 'context';

    /** @var int Characters of surrounding text quoted as evidence for a finding. */
    const EVIDENCE_CHARS = 180;

    /** @var int Most findings of any one kind to report, so one pathological file cannot flood a report. */
    const MAX_PER_CHECK = 12;

    /**
     * @var int Words per minute above which text was arriving in a document, not being written in it.
     *
     * Set from copy-typing speed (40-60 wpm), not composition speed (15-25), so that a learner
     * who drafted on paper and typed it up is never flagged for it. See provenance_findings().
     */
    const COMPOSITION_WPM_CEILING = 60;

    /**
     * @var int Shortest document the provenance proportionality checks apply to.
     *
     * A 40-word answer legitimately takes under a minute and records one save, so asking
     * whether its editing time is plausible is meaningless.
     */
    const PROVENANCE_MIN_WORDS = 200;

    /**
     * @var int Longest value kept from any one provenance field.
     *
     * Every provenance value comes out of a file the student uploaded, so its length is
     * theirs to choose. Uncapped, a crafted .docx carrying a 500 KB dc:creator was stored
     * verbatim - measured - and analysisjson is a TEXT column, 65,535 bytes on MySQL. One
     * upload would therefore fail the row write and lose the analysis for that submission.
     *
     * 256 characters is generous for everything real here: a person's name, an application
     * version string, an ISO timestamp, a PDF producer. Anything longer is not information,
     * and it is truncated rather than dropped so the report still shows that the field was
     * present and tampered with.
     */
    const PROVENANCE_FIELD_MAX = 256;

    /**
     * Conversational remnants from a chat assistant.
     *
     * Each entry is a case-insensitive regular expression. These are not stylistic
     * preferences, they are sentences that belong to a chat interface rather than to an
     * assessment, so a match is close to self-evident: a student would have to have typed
     * the assistant's own words into their answer.
     *
     * Kept deliberately narrow. Anything that a student might plausibly write by coincidence
     * is excluded, because a false accusation here is far more costly than a missed
     * detection. "In conclusion" is not in this list and never will be.
     *
     * @return array Map of regex => short label.
     */
    public static function assistant_artefact_patterns(): array {
        return [
            // Direct self-reference. No legitimate route into a student's assessment.
            '/\bas an? AI (?:language )?model\b/i'                 => 'AI self-reference',
            '/\bI\'?m an AI\b/i'                                   => 'AI self-reference',
            '/\bas a large language model\b/i'                     => 'AI self-reference',
            '/\bI (?:do not|don\'?t) have (?:personal )?(?:experiences|feelings|opinions)\b/i'
                                                                   => 'AI self-reference',
            '/\bI cannot browse the internet\b/i'                  => 'AI self-reference',
            '/\bmy (?:training data|knowledge cut-?off)\b/i'        => 'AI self-reference',

            // Chat framing left in place around a generated answer.
            '/\bhere(?:\'s| is) (?:a|an|your|the) (?:revised|rewritten|updated|improved|possible|sample|suggested)\b/i'
                                                                   => 'assistant framing',
            '/\bhere(?:\'s| is) (?:a|an) \d{2,4}\s*[-–to]+\s*\d{2,4}\s*word\b/i'
                                                                   => 'assistant framing',
            '/\bhere(?:\'s| is) how you (?:could|might|can) (?:answer|approach|phrase)\b/i'
                                                                   => 'assistant framing',
            '/^\s*(?:certainly|sure|absolutely|of course)[!,]\s/im' => 'assistant framing',
            '/\blet me know if you(?:\'?d| would) like\b/i'         => 'assistant framing',
            '/\bwould you like me to\b/i'                           => 'assistant framing',
            '/\bI hope this helps\b/i'                              => 'assistant framing',
            '/\bfeel free to (?:adjust|modify|tweak|personalise|personalize)\b/i'
                                                                   => 'assistant framing',
            '/\b(?:I\'?ve|I have) (?:rewritten|rephrased|simplified|expanded) (?:this|it|your)\b/i'
                                                                   => 'assistant framing',

            // The instruction, pasted in along with the answer it produced.
            '/\bword count\s*[:=]\s*\d{2,4}\b/i'                   => 'prompt remnant',
            '/\b(?:in|using|write in) (?:australian|british|american) english\b/i'
                                                                   => 'prompt remnant',
            '/\b(?:write|rewrite|make) (?:this|it) (?:sound )?(?:more )?(?:like a student|natural|simpler|less formal)\b/i'
                                                                   => 'prompt remnant',
            '/\bas if (?:written )?by a (?:student|learner)\b/i'    => 'prompt remnant',
            '/\b(?:answer|respond) in \d{2,4}\s*[-–to]+\s*\d{2,4} words\b/i'
                                                                   => 'prompt remnant',
            '/\b(?:approximately|about|around) \d{2,4} words\b/i'   => 'prompt remnant',
            '/^\s*(?:prompt|instruction)s?\s*:/im'                  => 'prompt remnant',
            '/^\s*={2,}\s*Q\s*\d+\s*={2,}\s*$/im'                   => 'prompt remnant',
        ];
    }

    /**
     * Find conversational artefacts and prompt remnants in extracted text.
     *
     * @param string $text Text as extracted from the submitted file.
     * @return array List of findings, each with check, label, severity, evidence and offset.
     */
    public static function assistant_artefacts(string $text): array {
        $findings = [];

        foreach (self::assistant_artefact_patterns() as $pattern => $label) {
            if (!preg_match_all($pattern, $text, $matches, PREG_OFFSET_CAPTURE)) {
                continue;
            }
            foreach ($matches[0] as [$matched, $offset]) {
                $findings[] = [
                    'check'    => 'assistant_artefact',
                    'label'    => $label,
                    'severity' => self::SEVERITY_STRONG,
                    'matched'  => trim($matched),
                    'offset'   => (int)$offset,
                    'evidence' => self::evidence($text, (int)$offset),
                ];
                if (count($findings) >= self::MAX_PER_CHECK) {
                    return $findings;
                }
            }
        }

        return $findings;
    }

    /**
     * Markdown syntax inside a word-processed submission.
     *
     * A Word document or PDF has its own formatting; it has no reason to contain markdown.
     * When it does, the text was composed somewhere that uses markdown - a chat interface,
     * most commonly - and pasted in.
     *
     * NOT STRONG on its own, and the reason matters: a student who drafts in a notes app, or
     * who has simply learned to type "**" for emphasis, produces the same marks. It is a
     * reason to look at how the document was assembled, not a conclusion.
     *
     * Bare hyphen bullets are excluded entirely. Plenty of people type "- " to make a list
     * and it would fire on a large share of honest submissions.
     *
     * @param string $text Text as extracted from the submitted file.
     * @return array List of findings.
     */
    public static function markdown_contamination(string $text): array {
        $patterns = [
            '/^\s{0,3}#{2,6}\s+\S/m'            => 'markdown heading',
            '/\*\*[^*\n]{2,80}\*\*/'            => 'markdown bold',
            '/(?<![\w*])\*[^*\n]{2,60}\*(?![\w*])/' => 'markdown italic',
            '/^\s{0,3}>\s+\S/m'                 => 'markdown blockquote',
            '/^\s{0,3}(?:\*|\+)\s+\S/m'         => 'markdown bullet',
            '/^\s{0,3}(?:---|___|\*\*\*)\s*$/m' => 'markdown horizontal rule',
            '/`{1,3}[^`\n]+`{1,3}/'             => 'markdown code span',
            '/\[[^\]\n]{1,80}\]\((?:https?:\/\/|www\.)[^)\s]+\)/' => 'markdown link',
        ];

        $findings = [];
        foreach ($patterns as $pattern => $label) {
            if (!preg_match_all($pattern, $text, $matches, PREG_OFFSET_CAPTURE)) {
                continue;
            }
            // One finding per KIND, carrying the count. Twelve bold spans are one
            // observation about the document, not twelve separate concerns.
            $first = $matches[0][0];
            $findings[] = [
                'check'    => 'markdown_contamination',
                'label'    => $label,
                'severity' => self::SEVERITY_NOTABLE,
                'count'    => count($matches[0]),
                'matched'  => trim((string)$first[0]),
                'offset'   => (int)$first[1],
                'evidence' => self::evidence($text, (int)$first[1]),
            ];
        }

        return $findings;
    }

