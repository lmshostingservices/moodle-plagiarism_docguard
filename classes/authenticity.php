    /**
     * Read provenance from a submitted file: what it records about how it was made.
     *
     * CONTEXT SEVERITY, ALWAYS, and the reason is not politeness. A document created from a
     * template, exported from Google Docs, produced on a phone, or typed up from handwritten
     * notes in one sitting all produce the same pattern as one that was pasted. These fields
     * answer "how was this file assembled", which is a useful question, and they do not answer
     * "who wrote the words".
     *
     * Absence of metadata is reported as absence. It is not evidence of anything - plenty of
     * perfectly ordinary pipelines strip it - and it must never read as a clean result.
     *
     * @param string $path Absolute path to a local copy of the submitted file.
     * @param string $filename Original filename, used only to pick the reader.
     * @param int $wordcount Words extracted, so editing time can be put in proportion.
     * @return array ['available' => bool, 'fields' => array, 'findings' => array]
     */
    public static function provenance(string $path, string $filename, int $wordcount = 0): array {
        $extension = strtolower(pathinfo($filename, PATHINFO_EXTENSION));

        if ($extension === 'docx') {
            $fields = self::docx_provenance($path);
        } else if ($extension === 'pdf') {
            $fields = self::pdf_provenance($path);
        } else {
            $fields = [];
        }

        // Findings are computed from the untruncated values - a date must not be cut before
        // it is parsed - then every value is capped before it is stored or displayed.
        $findings = $fields ? self::provenance_findings($fields, $wordcount) : [];

        foreach ($fields as $name => $value) {
            $value = (string)$value;
            if (\core_text::strlen($value) > self::PROVENANCE_FIELD_MAX) {
                $value = \core_text::substr($value, 0, self::PROVENANCE_FIELD_MAX) . '…';
            }
            // A control character in a metadata field has no legitimate purpose and would
            // break the JSON encode on the way into the database.
            $fields[$name] = (string)preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/u', '', $value);
        }

        return [
            'available' => !empty($fields),
            'fields'    => $fields,
            'findings'  => $findings,
        ];
    }

    /**
     * Read docProps/app.xml and docProps/core.xml out of a .docx package.
     *
     * @param string $path Absolute path to the .docx.
     * @return array Field name => value, for whichever fields are present.
     */
    protected static function docx_provenance(string $path): array {
        if (!class_exists('ZipArchive')) {
            return [];
        }
        $zip = new \ZipArchive();
        if ($zip->open($path) !== true) {
            return [];
        }
        $app  = (string)$zip->getFromName('docProps/app.xml');
        $core = (string)$zip->getFromName('docProps/core.xml');
        $zip->close();

        $pick = static function (string $xml, string $tag) {
            // Namespace prefix is not fixed across producers, so match on the local name.
            if (preg_match('~<(?:[A-Za-z0-9]+:)?' . preg_quote($tag, '~') . '\b[^>]*>(.*?)</~s', $xml, $m)) {
                $value = trim(html_entity_decode($m[1], ENT_QUOTES | ENT_XML1, 'UTF-8'));
                return $value === '' ? null : $value;
            }
            return null;
        };

        $fields = [
            'editing_minutes' => $pick($app, 'TotalTime'),
            'application'     => $pick($app, 'Application'),
            'app_version'     => $pick($app, 'AppVersion'),
            'declared_words'  => $pick($app, 'Words'),
            'created'         => $pick($core, 'created'),
            'modified'        => $pick($core, 'modified'),
            'revision'        => $pick($core, 'revision'),
            'creator'         => $pick($core, 'creator'),
            'last_modified_by' => $pick($core, 'lastModifiedBy'),
        ];

        return array_filter($fields, static fn($v) => $v !== null);
    }

    /**
     * Read the document information dictionary out of a PDF.
     *
     * Uses pdfinfo when it is available, because PDF metadata is frequently inside a
     * compressed object stream that a regular expression over the raw bytes cannot see. When
     * pdfinfo is absent the raw scan is attempted and will often find nothing, which is
     * reported honestly as no metadata rather than as a clean document.
     *
     * @param string $path Absolute path to the PDF.
     * @return array Field name => value.
     */
    protected static function pdf_provenance(string $path): array {
        $fields = [];

        $tools = extractor::extraction_tools();
        if (!empty($tools['pdftotext'])) {
            // poppler-utils present, so pdfinfo is beside pdftotext.
            $output = [];
            $status = 0;
            @exec('pdfinfo ' . escapeshellarg($path) . ' 2>/dev/null', $output, $status);
            if ($status === 0) {
                foreach ($output as $line) {
                    if (!preg_match('/^([A-Za-z ]+):\s+(.*)$/', $line, $m)) {
                        continue;
                    }
                    $key = strtolower(str_replace(' ', '_', trim($m[1])));
                    if (in_array($key, ['producer', 'creator', 'creationdate', 'moddate', 'pages', 'author'], true)) {
                        $value = trim($m[2]);
                        if ($value !== '') {
                            $fields[$key] = $value;
                        }
                    }
                }
            }
        }

        if (empty($fields)) {
            // Fallback: uncompressed info dictionary, which some producers still emit.
            $head = (string)@file_get_contents($path, false, null, 0, 400000);
            foreach (['Producer' => 'producer', 'Creator' => 'creator'] as $tag => $key) {
                if (preg_match('~/' . $tag . '\s*\(((?:[^()\\\\]|\\\\.){1,200})\)~', $head, $m)) {
                    $fields[$key] = trim($m[1]);
                }
            }
        }

        return $fields;
    }

    /**
     * Turn provenance fields into observations, where any are worth making.
     *
     * @param array $fields Output of docx_provenance() or pdf_provenance().
     * @param int $wordcount Words extracted from the document.
     * @return array List of findings, all at CONTEXT severity.
     */
    protected static function provenance_findings(array $fields, int $wordcount): array {
        $findings = [];

        $add = static function (string $label, string $detail) use (&$findings) {
            $findings[] = [
                'check'    => 'provenance',
                'label'    => $label,
                'severity' => self::SEVERITY_CONTEXT,
                'matched'  => $detail,
                'offset'   => null,
                'evidence' => null,
            ];
        };

        /*
         * Recorded editing time against length, in words per minute.
         *
         * COMPOSITION_WPM_CEILING is set from transcription speed, not composition speed.
         * Sustained composition of considered prose runs somewhere around 15 to 25 words a
         * minute; straight copy-typing from a page runs 40 to 60. Above 60 the words were not
         * being formed in that document, they were arriving in it - by paste, or by import.
         *
         * Deliberately set at the transcription ceiling rather than the composition rate,
         * because a learner who drafted on paper and typed it up is doing nothing wrong and
         * must not be flagged for it. That is also why this stays CONTEXT severity however
         * extreme the figure: a document assembled by paste is a fact about the file, and
         * drafting somewhere else - Google Docs, a phone, a notebook - is an ordinary and
         * legitimate way to work.
         *
         * The first version used 100 words per minute, which let 3 minutes for 285 words pass
         * unremarked. That is 95 words a minute, which nobody composes at.
         */
        if (isset($fields['editing_minutes']) && $wordcount >= self::PROVENANCE_MIN_WORDS) {
            $minutes = (int)$fields['editing_minutes'];
            if ($minutes >= 0 && $minutes < ($wordcount / self::COMPOSITION_WPM_CEILING)) {
                $add(
                    'recorded editing time is short for the length',
                    $minutes . ' minute(s) recorded for ' . $wordcount . ' words'
                );
            }
        }

        // One save, for a whole assessment.
        if (isset($fields['revision']) && (int)$fields['revision'] === 1
                && $wordcount >= self::PROVENANCE_MIN_WORDS) {
            $add('document records a single save', 'revision 1');
        }

        // Created and last modified within a couple of minutes of each other.
        if (isset($fields['created'], $fields['modified'])) {
            $created  = strtotime((string)$fields['created']);
            $modified = strtotime((string)$fields['modified']);
            if ($created && $modified && ($modified - $created) >= 0
                    && ($modified - $created) < 120
                    && $wordcount >= self::PROVENANCE_MIN_WORDS) {
                $add(
                    'whole document lifespan under two minutes',
                    'created and last modified ' . ($modified - $created) . ' seconds apart'
                );
            }
        }

        // Authored by someone other than the account that last saved it.
        if (isset($fields['creator'], $fields['last_modified_by'])
                && $fields['creator'] !== $fields['last_modified_by']) {
            $add(
                'created and last saved by different names',
                $fields['creator'] . ' / ' . $fields['last_modified_by']
            );
        }

        /*
         * PDF printed straight from a browser. Chrome's print-to-PDF writes Skia/PDF as the
         * producer, so a submission with that producer was printed from a web page rather
         * than exported from a word processor. Worth knowing, and no more than that: a
         * student may legitimately have written in a browser-based editor.
         */
        if (isset($fields['producer']) && preg_match('/\bskia\b/i', (string)$fields['producer'])) {
            $add('PDF printed from a browser page', (string)$fields['producer']);
        }

        return $findings;
    }

    /* ── Assembly and reporting ─────────────────────────────────────────────── */

    /**
     * Run every text-based check over one submission.
     *
     * @param string $text Text as extracted from the submitted file.
     * @return array List of findings, strongest first.
     */
    public static function text_findings(string $text): array {
        $findings = array_merge(
            self::assistant_artefacts($text),
            self::markdown_contamination($text),
            self::legislation_references($text)
        );

        return self::sort_findings($findings);
    }

    /**
     * Order findings so the decisive ones are read first.
     *
     * @param array $findings Findings in any order.
     * @return array The same findings, strongest first, then by position in the document.
     */
    public static function sort_findings(array $findings): array {
        $rank = [
            self::SEVERITY_STRONG  => 0,
            self::SEVERITY_NOTABLE => 1,
            self::SEVERITY_CONTEXT => 2,
        ];
        usort($findings, static function ($a, $b) use ($rank) {
            $byseverity = ($rank[$a['severity']] ?? 9) <=> ($rank[$b['severity']] ?? 9);
            if ($byseverity !== 0) {
                return $byseverity;
            }
            return ($a['offset'] ?? PHP_INT_MAX) <=> ($b['offset'] ?? PHP_INT_MAX);
        });

        return $findings;
    }

    /**
     * How many findings of each severity, for the report heading.
     *
     * Deliberately a count and not a score. There is no honest weighting of these against one
     * another without calibration on real student submissions, and a composite number is how
     * the previous version of this plugin came to display a confident badge derived from
     * signals that measured nothing. A trainer reads "two strong findings" correctly; they
     * read "71/100" as a probability it is not.
     *
     * @param array $findings Findings from text_findings() and provenance().
     * @return array ['strong' => int, 'notable' => int, 'context' => int]
     */
    public static function tally(array $findings): array {
        $tally = ['strong' => 0, 'notable' => 0, 'context' => 0];
        foreach ($findings as $finding) {
            $severity = $finding['severity'] ?? self::SEVERITY_CONTEXT;
            if (isset($tally[$severity])) {
                $tally[$severity]++;
            }
        }

        return $tally;
    }

    /**
     * Verification questions a trainer can ask about the learner's own submission.
     *
     * The most defensible authenticity mechanism available, and it does not depend on any
     * detection being right. If a learner can explain what they submitted, the question is
     * settled in their favour; if they cannot, that is a conversation about competence which
     * the trainer is qualified to have and the software is not.
     *
     * Built from the submission's own sentences by template, with no model involved, so the
     * text never leaves the server. The questions are prompts for a human conversation, not
     * an automated assessment.
     *
     * @param string $text Text as extracted from the submitted file.
     * @param int $limit Most questions to return.
     * @return array List of ['question' => string, 'basis' => string].
     */
    public static function verification_questions(string $text, int $limit = 4): array {
        $questions = [];

        // 1. Technical or regulatory terms the learner used, to explain in their own words.
        $terms = [];
        $phrases = [
            'reasonably practicable', 'duty of care', 'dignity of risk', 'hierarchy of control',
            'administrative control', 'engineering control', 'personal protective equipment',
            'temperature danger zone', 'cross contamination', 'duty holder', 'notifiable incident',
            'risk assessment', 'hazard identification', 'informed consent', 'mandatory reporting',
            'person conducting a business or undertaking', 'safe work method statement',
            'continuous improvement', 'scope of practice', 'confidentiality', 'open disclosure',
        ];
        foreach ($phrases as $phrase) {
            if (stripos($text, $phrase) !== false) {
                $terms[] = $phrase;
            }
        }
        foreach (array_slice($terms, 0, 2) as $term) {
            $questions[] = [
                'question' => 'You used the term "' . $term . '". Can you explain what that means '
                    . 'in your own words, and give an example from your own workplace?',
                'basis'    => 'term used in the submission',
            ];
        }

        // 2. Any citation made, so the learner can say where they found it.
        foreach (array_slice(self::legislation_references($text), 0, 1) as $reference) {
            $questions[] = [
                'question' => 'You referred to ' . $reference['matched'] . '. Where did you find '
                    . 'that requirement, and what does it ask an employer to do?',
                'basis'    => 'reference cited in the submission',
            ];
        }
        if (preg_match_all('/\b(?:Act|Regulations?|Standard|Code of Practice)\s+\d{4}\b/', $text, $m)
                && empty($questions[count($questions) - 1]['basis'] ?? null)) {
            $questions[] = [
                'question' => 'Which source did you use for the legal requirement you mentioned?',
                'basis'    => 'legal requirement referred to',
            ];
        }

        /*
         * 3. The longest sentence in the submission, read back. A learner explaining their own
         * reasoning manages this easily; it is specifically the sentences a learner did not
         * write that are hard to unpack on the spot.
         */
        $sentences = preg_split('/(?<=[.!?])\s+/u', trim(preg_replace('/\s+/u', ' ', $text)), -1, PREG_SPLIT_NO_EMPTY);
        $longest = '';
        foreach ((array)$sentences as $sentence) {
            $sentence = trim($sentence);
            $words = str_word_count($sentence);
            if ($words < 18 || $words > 60) {
                continue;
            }
            /*
             * Only the student's own account, never the assessment template.
             *
             * The first version of this took the longest sentence in the extracted text, which
             * on a real submission is the cover sheet: the header has no sentence punctuation,
             * so the RTO code, the unit title, the student's name and the instructions all
             * parse as one enormous sentence, and the trainer was handed "You wrote:
             * 'ASSESSMENT COVER SHEET Registered Training Organisation code 41234...' - can you
             * talk me through what you meant by that?" Asking a learner to explain their own
             * cover sheet would discredit the whole panel in one line.
             *
             * A first-person pronoun is the filter. These questions ask the learner to account
             * for their own narrative, which is exactly the part of the submission the template
             * did not supply. A submission with no first-person writing simply falls through to
             * the general question below rather than reaching for boilerplate.
             */
            if (!preg_match('/\b(?:I|I\'?m|I\'?ve|my|we|we\'?re|our|me|us)\b/i', $sentence)) {
                continue;
            }
            // Headings and form fields, which survive extraction as runs of capitals.
            if (preg_match('/\b[A-Z]{3,}\b/', $sentence)) {
                continue;
            }
            // Template language, in case a declaration is written in the first person -
            // which it is: "I declare that this assessment is my own work".
            if (preg_match('/\b(?:declare|declaration|assessment task|cover sheet|student id|'
                    . 'reasonably adjust|registered training organisation|plagiarism and cheating|'
                    . 'not yet satisfactory|instructions to the student)\b/i', $sentence)) {
                continue;
            }
            if (strlen($sentence) > strlen($longest)) {
                $longest = $sentence;
            }
        }
        if ($longest !== '') {
            $questions[] = [
                'question' => 'You wrote: "' . $longest . '" Can you talk me through what you meant '
                    . 'by that, and why it matters on the job?',
                'basis'    => 'sentence taken from the submission',
            ];
        }

        // 4. A fallback that always applies, so the trainer is never handed an empty list.
        $questions[] = [
            'question' => 'Tell me how you went about this assessment - what you read, what you '
                . 'drafted first, and anything or anyone that helped you.',
            'basis'    => 'general',
        ];

        return array_slice($questions, 0, max(1, $limit));
    }

    /**
     * Quote the text surrounding a finding, so the trainer sees it in context.
     *
     * @param string $text The full extracted text.
     * @param int $offset Byte offset of the match.
     * @return string A short excerpt, ellipsised, with whitespace collapsed.
     */
    protected static function evidence(string $text, int $offset): string {
        /*
         * BYTE offsets, cut with byte functions.
         *
         * preg_match_all() with PREG_OFFSET_CAPTURE returns byte offsets, with or without the
         * /u modifier. This used core_text::substr(), which is character-based, so the window
         * was taken from a position that drifted by one position for every multi-byte
         * character earlier in the document. Measured: 35 bytes of drift still landed inside
         * the window and looked fine; at 140 bytes the excerpt came out EMPTY, and beyond that
         * it was text from an unrelated part of the submission.
         *
         * That is 140 bytes, not 140 characters - about 45 accented letters, or a couple of
         * dozen uses of °C. A learner called Zoë describing a café fridge reaches it inside a
         * paragraph. The panel's whole claim is that the evidence is quoted so it can be
         * checked, so quoting the wrong passage, or nothing, is worse than having no panel.
         */
        $before = (int)floor(self::EVIDENCE_CHARS / 3);
        $start  = max(0, $offset - $before);
        $excerpt = (string)substr($text, $start, self::EVIDENCE_CHARS);

        /*
         * Either cut can land inside a multi-byte sequence. Drop the orphaned continuation
         * bytes at the front, then shorten from the end until what remains is valid UTF-8 -
         * at most three bytes, since that is the longest incomplete tail possible. Storing
         * invalid UTF-8 would be rejected by MySQL under utf8mb4 (the same class of failure
         * as FIX-DG-MB-TRUNCATE) and would corrupt the JSON encode on the way in.
         */
        $excerpt = (string)preg_replace('/^[\x80-\xBF]+/', '', $excerpt);
        for ($trim = 0; $trim < 4 && $excerpt !== '' && !mb_check_encoding($excerpt, 'UTF-8'); $trim++) {
            $excerpt = (string)substr($excerpt, 0, -1);
        }

        /*
         * Still invalid means the extraction itself carries bad bytes, not that the window was
         * cut badly - a damaged PDF, or a .docx written by something that mislabelled its
         * encoding. Keep the readable part rather than discarding the excerpt: dropping it
         * leaves the trainer looking at a finding with no context at all, which is the same
         * failure the byte-offset bug caused. mb_convert_encoding() from UTF-8 to UTF-8 removes
         * the invalid sequences and leaves the rest intact.
         */
        if (!mb_check_encoding($excerpt, 'UTF-8')) {
            $excerpt = (string)mb_convert_encoding($excerpt, 'UTF-8', 'UTF-8');
            if (!mb_check_encoding($excerpt, 'UTF-8')) {
                return '';
            }
        }

        $excerpt = trim((string)preg_replace('/\s+/u', ' ', $excerpt));
        if ($excerpt === '') {
            return '';
        }

        return ($start > 0 ? '…' : '') . $excerpt . '…';
    }
