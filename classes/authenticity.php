    /**
     * Extract and check every citation the text makes to a named Act or Regulation.
     *
     * Three kinds of finding come out of this:
     *   - the Act is not in the registry (reported as not recognised, not as fabricated);
     *   - the Act is real but the year is wrong (a strong finding, and a common signature of
     *     a reference that was generated rather than looked up);
     *   - the citation names a section number, which is quoted so a trainer can check it.
     *
     * @param string $text Text as extracted from the submitted file.
     * @return array List of findings.
     */
    public static function legislation_references(string $text): array {
        $registry = self::legislation_registry();
        $findings = [];
        $seen = [];

        /*
         * "<Title> Act|Regulations <year>", with the title limited to words that can appear
         * in one: capitalised words, "and", "of", "the", and parenthesised qualifiers such as
         * "(Care and Protection)". Anchored on the Act/Regulations keyword and the year, so
         * ordinary prose cannot match.
         */
        // One word of a title: a capitalised word, a lowercase connector, or a parenthesised
        // qualifier such as "(Care and Protection)".
        $titleword = '(?:[A-Z][A-Za-z\'-]+|and|of|the|\([A-Za-z\s]+\))';
        $pattern = '/\b(' . $titleword . '(?:\s+' . $titleword . '){0,9})\s+'
            . '(Act|Regulations?|Law)\s+(?:\(\s*[A-Za-z]{2,3}\s*\)\s*)?(\d{4})\b/';

        if (!preg_match_all($pattern, $text, $matches, PREG_SET_ORDER | PREG_OFFSET_CAPTURE)) {
            return $findings;
        }

        foreach ($matches as $match) {
            [$whole, $offset] = $match[0];
            $title = trim(preg_replace('/\s+/', ' ', $match[1][0]));
            $kind  = $match[2][0];
            $year  = (int)$match[3][0];

            /*
             * Strip the words that carried the citation into the sentence.
             *
             * The title pattern has to allow lowercase connectors ("and", "of", "the") so it
             * can match "Work Health and Safety Act" and "Children and Young Persons (Care
             * and Protection) Act". That also lets it swallow the preposition in front:
             * "under Section 19 of the Work Health and Safety Act 2011" captured as "of the
             * Work Health and Safety", which missed the registry and reported a correctly
             * cited Act as unrecognised. A false finding against a student who cited the law
             * properly is the worst failure this class can have, so the leading connectors
             * come off before the lookup. No Act title begins with one.
             */
            $leading = '/^(?:of|the|under|in|to|by|per|with|a|an|and|see|from)\s+/i';
            // Repeated, because a citation can arrive behind more than one of them
            // ("as set out in the ...", "of the ..."). One pass is not enough.
            while (preg_match($leading, $title)) {
                $title = preg_replace($leading, '', $title);
            }
            $title = trim($title);
            if ($title === '') {
                continue;
            }

            // Normalise to the registry's key shape: lowercase, Regulation(s) singularised.
            $key = strtolower($title . ' ' . preg_replace('/^Regulations?$/i', 'Regulations', $kind));
            $key = preg_replace('/\s+/', ' ', $key);

            $dedupe = $key . '|' . $year;
            if (isset($seen[$dedupe])) {
                continue;
            }
            $seen[$dedupe] = true;

            if (!isset($registry[$key])) {
                $findings[] = [
                    'check'    => 'reference_unrecognised',
                    'label'    => 'not in the recognised list',
                    'severity' => self::SEVERITY_NOTABLE,
                    'matched'  => trim($whole),
                    'offset'   => (int)$offset,
                    'evidence' => self::evidence($text, (int)$offset),
                ];
                continue;
            }

            $entry = $registry[$key];
            if (!in_array($year, $entry['years'], true)) {
                $findings[] = [
                    'check'    => 'reference_wrong_year',
                    'label'    => 'real Act, year does not exist',
                    'severity' => self::SEVERITY_STRONG,
                    'matched'  => trim($whole),
                    'expected' => implode(', ', $entry['years']),
                    'jurisdiction' => $entry['jurisdiction'],
                    'offset'   => (int)$offset,
                    'evidence' => self::evidence($text, (int)$offset),
                ];
            }

            if (count($findings) >= self::MAX_PER_CHECK) {
                break;
            }
        }

        return $findings;
    }

    /*
     * REMOVED BEFORE RELEASE: a unit-of-competency code format check.
     *
     * The idea was to flag codes that cannot be real because they are malformed - leaving
     * whether a well-formed code actually EXISTS to training.gov.au, which is out of scope
     * here for the same reasons as a live legislation lookup.
     *
     * It was written, tested, and failed its own test on the first real code it saw. The
     * format was taken to be three to six letters then three or four digits, which rejects
     * SITXFSA005 and SITXFSA006 - seven letters, both entirely valid. Widening the rule to
     * cover the real spread (TLILIC0003, CPCCWHS1001, CHCCCS031, HLTAID011) makes it almost
     * identical to the pattern used to FIND candidates in the first place, so it would
     * approve everything and discriminate nothing.
     *
     * Unit code shapes vary too much across training packages to validate by pattern. The
     * check is not here because a check that flags a real unit code as invalid is worse than
     * no check at all, and a vacuous one that always passes is worse still: it would sit in
     * the report implying something had been verified. Code verification belongs with a
     * training.gov.au lookup, scoped separately.
     */

